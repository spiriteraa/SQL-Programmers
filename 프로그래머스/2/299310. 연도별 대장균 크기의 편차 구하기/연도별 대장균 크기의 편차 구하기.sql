SELECT YEAR(DIFFERENTIATION_DATE) AS YEAR, (Y.MAX - D.SIZE_OF_COLONY) AS YEAR_DEV, ID
FROM ECOLI_DATA AS D
JOIN (
    SELECT YEAR(DIFFERENTIATION_DATE) AS YEAR, MAX(SIZE_OF_COLONY) AS 'MAX'
    FROM ECOLI_DATA
    GROUP BY YEAR(DIFFERENTIATION_DATE)
    ) AS Y ON Y.YEAR = YEAR(DIFFERENTIATION_DATE)
ORDER BY YEAR ASC, YEAR_DEV ASC;